/**
 * Centralized UI dictionaries for the two supported site languages.
 *
 * The English dictionary is the source of truth for the key set — the Khmer
 * dictionary mirrors its shape. `translate()` falls back to English for any
 * key that is missing in the active locale so the UI never renders raw keys.
 *
 * News content itself is NOT translated here — this file covers interface
 * chrome only (navigation, buttons, labels, empty/loading/error states).
 */

